// Translate only the known ranking envelope; evidence remains user content.
export function localizeRankingReason(language, reason) {
  const raw = String(reason || '');
  if (normalizeLanguage(language) !== 'zh') return raw;
  if (raw === 'Recency fallback — no AI assessment') return translate(language, raw);
  const prefix = 'AI assessment + recency; evidence: ';
  if (!raw.startsWith(prefix)) return raw;
  const penalty = ' (superseded penalty)';
  const hasPenalty = raw.endsWith(penalty);
  return 'AI 评估 + 最近活动；依据：' + raw.slice(prefix.length, hasPenalty ? -penalty.length : undefined) + (hasPenalty ? '（已被替代，降低排序）' : '');
}
